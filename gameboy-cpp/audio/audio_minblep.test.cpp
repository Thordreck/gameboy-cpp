    template <typename TExpected, typename TError>
    [[nodiscard]] TExpected required(std::expected<TExpected, TError>&& result)
    {
        REQUIRE_MESSAGE(result.has_value(), std::format("Unexpected error. {}", result.error()));
        return std::forward<TExpected>(result.value());
    }

    template <typename TError>
    void required(std::expected<void, TError>&& result)
    {
        REQUIRE_MESSAGE(result.has_value(), std::format("Unexpected error. {}", result.error()));
    }

    [[nodiscard]] std::filesystem::path get_temp_file(const std::string_view extension)
    {
        using namespace utils;
        namespace files = std::filesystem;

        return (files::temp_directory_path() / generate_uuid()).replace_extension(extension);
    }

    [[nodiscard]] std::expected<std::filesystem::path, std::string> export_plot(plot::figure& figure)
    {
        using namespace plot;
        using namespace svg;

        std::stringstream svg_export_stream{};
        required(save_as_svg(figure, svg_export_stream));

        const std::filesystem::path output_filepath = get_temp_file(".png");

        return document::load(svg_export_stream.view().data(), svg_export_stream.str().size())
               .and_then([](auto doc) { return doc.to_bitmap(); })
               .and_then([&output_filepath](auto bitmap) { return bitmap.save_as_png(output_filepath); })
               .transform([&output_filepath] { return output_filepath; });
    }

    void populate_time_plot(plot::plot_2d& plot, plot::Indexable<float> auto const& samples)
    {
        using namespace plot;

        const auto t = std::views::iota(0uz, samples.size())
            | std::views::transform([](const auto i) { return static_cast<float>(i); });

        plot.line()
            .add(t, samples);

        plot.y()
            .minors(tick{0 }, tick{1 }, tick{1.5 });
    }

	void populate_spectrum_plot(
		plot::plot_2d& plot,
		plot::Indexable<float> auto const& spectrum,
		const float nfft,
		const float oversampling)
	{
		using namespace plot;
		const auto max_fft_value = std::ranges::max(spectrum);

		const auto freqs
			= std::views::iota(0uz, spectrum.size())
			| std::views::transform([nfft, oversampling] (const auto i) { return (i / static_cast<double>(nfft)) * oversampling; });

		constexpr size_t x_ticks_chunk_size { 10 };

		const auto x_ticks
			= std::views::enumerate(spectrum)
			| std::views::chunk(spectrum.size() / x_ticks_chunk_size)
			| std::views::transform([] (const auto& window)
				{
					const auto compare_fft_y = [] (const auto& lhs, const auto& rhs) { return std::get<1>(lhs) < std::get<1>(rhs); };
					return std::ranges::max_element(window, compare_fft_y);
				})
			| std::views::filter([max_fft_value] (const auto max_it)
				{
					const auto threshold = max_fft_value * 0.1f;
					return std::get<1>(*max_it) > threshold;
				})
			| std::views::transform([] (const auto max_it) { return std::get<0>(*max_it); })
			| std::views::transform([nfft, oversampling] (const auto i)
				{
					const auto hz = (i / static_cast<double>(nfft)) * oversampling;
					return tick { hz, std::format("{}", std::round(hz)) };
				});

		plot.line()
			.add(freqs, spectrum);

		// Note: it's not possible to iterate a const std::views::filter, since iterating it affects its internal state.
		// We can either remove the const from the x_ticks declaration or create a copy using the auto() operator.
		plot.x()
			.label("normalized frequency")
			.minors(auto(x_ticks));

		plot.y()
			.minors(tick { 0 }, tick { max_fft_value, std::format("{:.2f}", max_fft_value) } );
	}

	void populate_correlation_plot(plot::plot_2d& plot, plot::Indexable<double> auto const& correlation, const size_t original_length)
    {
    	using namespace plot;

    	const auto compute_lag = [original_length] (const size_t i) { return static_cast<double>(i) - original_length - 1; };
    	const auto max_correlation_it = std::ranges::max_element(correlation);
    	const auto max_correlation_index = std::ranges::distance(correlation.begin(), max_correlation_it);
    	const auto x = std::views::iota(0uz, correlation.size()) | std::views::transform(compute_lag);
    	const auto max_correlation_lag = compute_lag(max_correlation_index);

    	plot.line().add(x, correlation);
    	plot.x().minor(tick { max_correlation_lag, std::format("max = {:.2f} at lag = {:.1f} samples)", *max_correlation_it, max_correlation_lag) });

    	plot.y()
			.minors(tick { -1 }, tick { 0 }, tick { 1 } );
    }
